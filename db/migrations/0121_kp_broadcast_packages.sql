-- Personal cosmetic broadcast identity; owned by player, not show state.
CREATE TABLE ppw_kp_broadcast_packages (
 player_id text PRIMARY KEY REFERENCES ppw_players(player_id) ON DELETE CASCADE,
 style text NOT NULL CHECK(style IN ('PRIME_TIME_COMBAT','SATURDAY_NIGHT_TERRITORY','MIDNIGHT_FREQUENCY','PRIZEFIGHT','RENEGADE_TV','THE_GRAND_STAGE','BOOKERVISION_2002','STRONG_STYLE_NETWORK','LUCHA_FIESTA'))
);
ALTER TABLE ppw_kp_receipts DROP CONSTRAINT ppw_kp_receipts_kind_check;
