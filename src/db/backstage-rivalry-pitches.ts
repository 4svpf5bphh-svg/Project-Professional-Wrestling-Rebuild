/** An original PPW wrestler-led feud suggestion.
 * Requires two different certified singles shows against the same opponent,
 * strong audience response, a trustworthy working relationship, and access
 * to both performers. This is NOT an AI-authored scripted feud.
 */
import type {SqlRows} from "./world-operations.js";
export async function publishBackstageRivalryPitches(
 tx:SqlRows,worldId:string,weekIndex:number,
){
 if(!worldId||!Number.isSafeInteger(weekIndex)||weekIndex<0)
  throw new Error("Invalid Backstage rivalry week");
 const rows=await tx.query<{request_id:string}>([
  "WITH completed AS (",
  "SELECT sh.promotion_id,sh.show_id,played.crowd_response,",
  "least(s.payload->'participants'->0->>'personId',",
  "s.payload->'participants'->1->>'personId') AS person_a_id,",
  "greatest(s.payload->'participants'->0->>'personId',",
  "s.payload->'participants'->1->>'personId') AS person_b_id,",
  "s.payload->'participants'->0->>'contractId' AS first_contract,",
  "s.payload->'participants'->1->>'contractId' AS second_contract,",
  "s.payload->'participants'->0->>'personId' AS first_person,",
  "s.payload->'participants'->1->>'personId' AS second_person",
  "FROM ppw_completed_shows sh JOIN ppw_completed_show_matches played",
  "ON played.world_id=sh.world_id AND played.show_id=sh.show_id",
  "JOIN ppw_card_slots s ON s.world_id=played.world_id",
  "AND s.draft_id=played.show_id AND s.slot_id=played.match_id",
  "WHERE sh.world_id=$1 AND s.kind='MATCH'",
  "AND (sh.year-1)*52+sh.week-1 BETWEEN greatest(0,$2-12) AND $2-1",
  "AND jsonb_typeof(s.payload->'participants')='array'",
  "AND jsonb_array_length(s.payload->'participants')=2",
  "AND (s.payload->>'matchType' IS NULL OR s.payload->>'matchType'='SINGLES')",
  "AND (s.payload->>'family' IS NULL OR s.payload->>'family'='INDIVIDUAL')",
  "), verified AS (",
  "SELECT c.promotion_id,c.person_a_id,c.person_b_id,",
  "count(DISTINCT c.show_id)::integer AS shared_shows,",
  "round(avg(c.crowd_response)::numeric,1) AS average_crowd,",
  "max(rel.professional_trust) AS professional_trust",
  "FROM completed c",
  "JOIN ppw_wrestler_relationships rel ON rel.world_id=$1",
  "AND rel.person_a_id=c.person_a_id AND rel.person_b_id=c.person_b_id",
  "AND rel.professional_trust>=60",
  "JOIN ppw_contracts a ON a.world_id=$1",
  "AND a.promotion_id=c.promotion_id AND a.person_id=c.first_person",
  "AND a.contract_id=c.first_contract AND a.status='SIGNED'",
  "AND a.start_week_index<=$2 AND a.expires_week_index>=$2",
  "AND (a.remaining_dates IS NULL OR a.remaining_dates>0)",
  "JOIN ppw_contracts b ON b.world_id=$1",
  "AND b.promotion_id=c.promotion_id AND b.person_id=c.second_person",
  "AND b.contract_id=c.second_contract AND b.status='SIGNED'",
  "AND b.start_week_index<=$2 AND b.expires_week_index>=$2",
  "AND (b.remaining_dates IS NULL OR b.remaining_dates>0)",
  "JOIN ppw_people pa ON pa.world_id=$1 AND pa.person_id=c.person_a_id",
  "AND pa.status='ACTIVE'",
  "JOIN ppw_people pb ON pb.world_id=$1 AND pb.person_id=c.person_b_id",
  "AND pb.status='ACTIVE'",
  "JOIN ppw_promotion_controls owner ON owner.world_id=$1",
  "AND owner.promotion_id=c.promotion_id AND owner.active",
  "JOIN ppw_memberships member ON member.world_id=$1",
  "AND member.player_id=owner.player_id AND member.status='ACTIVE'",
  "WHERE c.person_a_id<>c.person_b_id",
  "AND NOT EXISTS(SELECT 1 FROM ppw_programmes programme",
  "JOIN ppw_programme_participants pa ON pa.world_id=programme.world_id",
  "AND pa.promotion_id=programme.promotion_id",
  "AND pa.programme_id=programme.programme_id AND pa.person_id=c.person_a_id",
  "JOIN ppw_programme_participants pb ON pb.world_id=programme.world_id",
  "AND pb.promotion_id=programme.promotion_id",
  "AND pb.programme_id=programme.programme_id AND pb.person_id=c.person_b_id",
  "AND pb.side<>pa.side",
  "WHERE programme.world_id=$1 AND programme.promotion_id=c.promotion_id",
  "AND programme.status='ACTIVE')",
  "AND NOT EXISTS(SELECT 1 FROM ppw_backstage_requests earlier",
  "WHERE earlier.world_id=$1 AND earlier.promotion_id=c.promotion_id",
  "AND earlier.kind='RIVALRY_PITCH'",
  "AND earlier.person_id=c.person_a_id",
  "AND earlier.related_person_id=c.person_b_id",
  "AND earlier.created_week_index>=greatest(0,$2-52))",
  "AND NOT EXISTS(SELECT 1 FROM ppw_backstage_requests pending",
  "WHERE pending.world_id=$1 AND pending.promotion_id=c.promotion_id",
  "AND pending.person_id=c.person_a_id",
  "AND (pending.status IN ('PENDING','PROMISED')",
  "OR pending.created_week_index>=$2-8))",
  "AND NOT EXISTS(SELECT 1 FROM ppw_backstage_requests this_week",
  "WHERE this_week.world_id=$1 AND this_week.promotion_id=c.promotion_id",
  "AND this_week.created_week_index=$2)",
  "AND (SELECT count(*) FROM ppw_backstage_requests pending",
  "WHERE pending.world_id=$1 AND pending.promotion_id=c.promotion_id",
  "AND pending.status='PENDING')<3",
  "GROUP BY c.promotion_id,c.person_a_id,c.person_b_id",
  "HAVING count(DISTINCT c.show_id)>=2 AND avg(c.crowd_response)>=70",
  "), ranked AS (",
  "SELECT *,row_number() OVER(PARTITION BY promotion_id",
  "ORDER BY average_crowd DESC,shared_shows DESC,",
  "professional_trust DESC,person_a_id,person_b_id) AS rank FROM verified)",
  "INSERT INTO ppw_backstage_requests(",
  "world_id,request_id,promotion_id,person_id,related_person_id,",
  "kind,created_week_index,rival_verified_matches,",
  "observed_average_crowd,rival_professional_trust)",
  "SELECT $1,'backstage:rival:'||promotion_id||':'||person_a_id||':'||",
  "person_b_id||':year'||($2/52+1)::text,",
  "promotion_id,person_a_id,person_b_id,'RIVALRY_PITCH',$2,",
  "shared_shows,average_crowd,professional_trust",
  "FROM ranked WHERE rank=1 ON CONFLICT DO NOTHING RETURNING request_id"
 ].join(" "),[worldId,weekIndex]);
 if(rows.length>128)throw new Error("Backstage rivalry pitches exceed World cap");
 return {newPitches:rows.length};
}
/** This receipt is recorded only if the booker really starts the two-sided
 * programme after considering the pitch. No feud, heat or finish is invented.
 */
export async function settleBackstageRivalryFollowThrough(
 tx:SqlRows,worldId:string,weekIndex:number,
){
 const rows=await tx.query<{request_id:string}>([
  "WITH evidence AS (",
  "SELECT DISTINCT ON (r.request_id) r.request_id,programme.started_week_index",
  "FROM ppw_backstage_requests r",
  "JOIN ppw_programmes programme ON programme.world_id=r.world_id",
  "AND programme.promotion_id=r.promotion_id",
  "AND programme.started_week_index BETWEEN r.responded_week_index AND $2",
  "JOIN ppw_programme_participants a ON a.world_id=programme.world_id",
  "AND a.promotion_id=programme.promotion_id",
  "AND a.programme_id=programme.programme_id AND a.person_id=r.person_id",
  "JOIN ppw_programme_participants b ON b.world_id=programme.world_id",
  "AND b.promotion_id=programme.promotion_id",
  "AND b.programme_id=programme.programme_id",
  "AND b.person_id=r.related_person_id AND b.side<>a.side",
  "WHERE r.world_id=$1 AND r.kind='RIVALRY_PITCH'",
  "AND r.decision='EXPLORE_RIVALRY' AND r.status='ANSWERED'",
  "AND r.follow_through_week_index IS NULL",
  "AND r.responded_week_index>=$2-26",
  "ORDER BY r.request_id,programme.started_week_index,programme.programme_id",
  ") UPDATE ppw_backstage_requests r SET",
  "follow_through_week_index=e.started_week_index,",
  "follow_through_kind='RIVALRY_PROGRAMME_STARTED'",
  "FROM evidence e WHERE r.world_id=$1 AND r.request_id=e.request_id",
  "AND r.follow_through_week_index IS NULL RETURNING r.request_id"
 ].join(" "),[worldId,weekIndex]);
 if(rows.length>512)throw new Error("Rivalry follow-through exceeds World cap");
 return {followedThrough:rows.length};
}
