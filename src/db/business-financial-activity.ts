/** Cash movements are canonical ledger receipts, not reconstructed
 * transactions or additional materialized finance snapshots. Scoped to the
 * player's promotion and at most four closed/current weeks.
 */
export const recentFinanceSql=[
 "LEFT JOIN LATERAL (",
 "WITH events AS MATERIALIZED (",
 "SELECT e.event_id,e.year,e.week,e.event_type,e.payload",
 "FROM ppw_ledger_events e",
 "WHERE e.world_id=p.world_id AND e.payload->>'promotionId'=p.promotion_id",
 "AND e.event_type IN ('CONTRACT_SIGNED','CONTRACT_EXTRA_DATES_ACCEPTED',",
 "'CONTRACT_APPEARANCE_FEES','CONTRACT_GUARANTEE_PAID',",
 "'CONTRACT_TERMINATED_DURING_RESTRUCTURING',",
 "'PROMOTION_RECURRING_FINANCES','SHOW_EVENT_ECONOMICS')",
 "AND ((e.year=w.year AND e.week BETWEEN greatest(1,w.week-3) AND w.week)",
 "OR (w.week<=3 AND e.year=w.year-1",
 "AND e.week BETWEEN 49+w.week AND 52))",
 "ORDER BY e.event_id DESC LIMIT 501",
 "), lines AS MATERIALIZED (",
 "SELECT e.event_id,e.year,e.week,item.category,item.amount",
 "FROM events e CROSS JOIN LATERAL (VALUES",
 "('MEDIA_INCOME',CASE WHEN e.event_type='PROMOTION_RECURRING_FINANCES'",
 "THEN (e.payload->>'mediaIncome')::bigint END),",
 "('SPONSOR_INCOME',CASE WHEN e.event_type='PROMOTION_RECURRING_FINANCES'",
 "THEN (e.payload->>'sponsorIncome')::bigint END),",
 "('FIXED_OVERHEAD',CASE WHEN e.event_type='PROMOTION_RECURRING_FINANCES'",
 "THEN -(e.payload->>'fixedOverhead')::bigint END),",
 "('STAFF_SALARY',CASE WHEN e.event_type='PROMOTION_RECURRING_FINANCES'",
 "THEN -(e.payload->>'staffCost')::bigint END),",
 "('CONTRACT_GUARANTEE',CASE WHEN e.event_type='CONTRACT_GUARANTEE_PAID'",
 "THEN -(e.payload->>'amount')::bigint END),",
 "('RESTRUCTURING_SETTLEMENT',CASE WHEN",
 "e.event_type='CONTRACT_TERMINATED_DURING_RESTRUCTURING'",
 "THEN -(e.payload->>'settlement')::bigint END),",
 "('CONTRACT_SIGNING_BONUS',CASE WHEN e.event_type='CONTRACT_SIGNED'",
 "THEN -(e.payload->>'signingBonus')::bigint END),",
 "('EXTRA_DATES',CASE WHEN e.event_type='CONTRACT_EXTRA_DATES_ACCEPTED'",
 "THEN -(e.payload->>'additionalPayment')::bigint END),",
 "('APPEARANCE_FEE',CASE WHEN e.event_type='CONTRACT_APPEARANCE_FEES'",
 "THEN -(e.payload->>'amount')::bigint END),",
 "('GATE_REVENUE',CASE WHEN e.event_type='SHOW_EVENT_ECONOMICS'",
 "THEN (e.payload->>'gateRevenue')::bigint END),",
 "('VENUE_COST',CASE WHEN e.event_type='SHOW_EVENT_ECONOMICS'",
 "THEN -(e.payload->>'venueCost')::bigint END),",
 "('PRODUCTION_COST',CASE WHEN e.event_type='SHOW_EVENT_ECONOMICS'",
 "THEN -(e.payload->>'productionCost')::bigint END),",
 "('TRAVEL_COST',CASE WHEN e.event_type='SHOW_EVENT_ECONOMICS'",
 "THEN -(e.payload->>'travelCost')::bigint END)",
 ") AS item(category,amount)",
 "WHERE item.amount IS NOT NULL AND item.amount<>0",
 "), totals AS (",
 "SELECT category,sum(amount)::bigint AS amount FROM lines GROUP BY category",
 ")",
 "SELECT (SELECT count(*)::integer FROM events) AS finance_event_count,",
 "coalesce((SELECT jsonb_agg(jsonb_build_object('category',category,",
 "'amount',amount) ORDER BY abs(amount) DESC,category) FROM totals),",
 "'[]'::jsonb) AS finance_categories,",
 "coalesce((SELECT jsonb_agg(jsonb_build_object(",
 "'eventId',event_id,'year',year,'week',week,'category',category,",
 "'amount',amount) ORDER BY event_id DESC,category) FROM",
 "(SELECT * FROM lines ORDER BY event_id DESC,category LIMIT 8) last),",
 "'[]'::jsonb) AS finance_recent",
 ") financial ON true"
].join(" ");
export type FinanceLine={category:string;amount:number};
export type FinanceEntry=FinanceLine&{eventId:number;year:number;week:number};
